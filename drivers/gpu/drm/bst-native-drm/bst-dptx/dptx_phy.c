#define RAWLANEN_DIG_FSM_FSM_OVRD_CTL  0x3020
# define FSM_OVRD_EN   BIT(14)
# define FSM_CMD_START BIT(13)
# define FSM_JMP_EN    BIT(12)
# define FSM_JMP_ADDR  GENMASK(11, 0)

#define RAWCMN_DIG_AON_CMN_SRAM_BL_CFG 0x2038
# define SRAM_PGATE_BL_EN      BIT(0)
# define SRAM_BL_ROM      BIT(1)
# define SRAM_BL_BYPASS   BIT(2)
# define SRAM_BL_START    BIT(3)

void dptx_phy_firmware_load_from(struct dptx *dptx,
				     enum dptx_phy_boot_type type)
{
	uint8_t sram_bypass = 1;
	uint8_t sram_ext_ld_done = 0;
	uint32_t phy_ctrl;

	switch (type) {
	case ONLY_ROM:
		sram_bypass = 1;
		sram_ext_ld_done = 0;
		break;
	case OVERRD_SRAM: /* second */
		sram_bypass = 0;
		sram_ext_ld_done = 0;
		break;
	case ONLY_ROM_TRIG:
	case OVERRD_SRAM_TRIG:
	case ROM_TO_SRAM_TRIG:
	case USE_SRAM_PREV_TRIG:
	case SRAM_PREV_POR_TRIG:
	case SRAM_PRE_FLASHED_TRIG:
	case ONLY_SRAM: /* 3 */
		sram_bypass = 1;
		sram_ext_ld_done = 1;
		break;
	default:
		break;
	}
	phy_ctrl = dptx_read_reg(dptx, dptx->regs[DPTX_CSR], EDP_CSR_PHY_CTRL0);
	phy_ctrl = sram_bypass ? (phy_ctrl | CSR_PHY0_SRAM_BYPASS) :
				 (phy_ctrl & ~CSR_PHY0_SRAM_BYPASS);
	phy_ctrl = sram_ext_ld_done ? (phy_ctrl | CSR_PHY0_SRAM_EXT_LD_DONE) :
				      (phy_ctrl & ~CSR_PHY0_SRAM_EXT_LD_DONE);
	dptx_write_reg(dptx, dptx->regs[DPTX_CSR], EDP_CSR_PHY_CTRL0, phy_ctrl);
}


uint32_t dptx_u3_phy_read_reg(struct dptx *dptx, uint32_t addr)
{
	int status_ack = 1;
	uint32_t val = ((addr << 16) & GENMASK(31, 16));

	dptx_write_reg(dptx, dptx->regs[DPTX_CSR], EDP_CSR_PHY0_CR_CTRL0, val);
	dptx_write_reg(dptx, dptx->regs[DPTX_CSR], EDP_CSR_W1N_CTRL, BIT(0));
	// printf("sram init done %#x\n", dptx_read_reg(dptx, dptx->regs[DPTX_CSR], EDP_CSR_PHY_STATE));
	while (status_ack == 1) {
		status_ack = (dptx_read_reg(dptx, dptx->regs[DPTX_CSR], EDP_CSR_PHY0_CR_PARA_STATE) &
			      BIT(0));
	}
	return (dptx_read_reg(dptx, dptx->regs[DPTX_CSR], EDP_CSR_PHY0_CR_PARA_STATE) &
		GENMASK(31, 16)) >>
	       16;
}
void dptx_u3_phy_write_reg(struct dptx *dptx, uint32_t addr,
				     uint32_t data)
{
	int status_ack = 1;
	uint32_t init_done = 0;
	uint32_t val = (data & GENMASK(15, 0));
	val |= ((addr << 16) & GENMASK(31, 16));

	dptx_write_reg(dptx, dptx->regs[DPTX_CSR], EDP_CSR_PHY0_CR_CTRL0, val);
	dptx_write_reg(dptx, dptx->regs[DPTX_CSR], EDP_CSR_W1N_CTRL, BIT(1));
	do {
		init_done = dptx_read_reg(dptx, dptx->regs[DPTX_CSR], EDP_CSR_PHY_STATE);
		if (init_done & BIT(1)) {
			break;
		}
	} while(!(val & BIT(1)));
	while (status_ack == 1) {
		status_ack = (dptx_read_reg(dptx, dptx->regs[DPTX_CSR], EDP_CSR_PHY0_CR_PARA_STATE) &
			      BIT(0));
	}
}

/* load phy firmware frome external */
void dptx_write_cr_reg(struct dptx *dptx)
{
	int i;

	dptx_dbg(dptx, "first addr:%#x data:%#x\n", usb3dptx_phy_firmware[0].addr, usb3dptx_phy_firmware[0].data);
	dptx_dbg(dptx, "last addr:%#x data:%#x\n", usb3dptx_phy_firmware[sizeof(usb3dptx_phy_firmware) / sizeof(struct u3_phy_data) - 1].addr, usb3dptx_phy_firmware[sizeof(usb3dptx_phy_firmware) / sizeof(struct u3_phy_data) - 1].data);
	for (i = 0;i < sizeof(usb3dptx_phy_firmware) / sizeof(struct u3_phy_data); i++) {
		dptx_u3_phy_write_reg(dptx, usb3dptx_phy_firmware[i].addr, usb3dptx_phy_firmware[i].data);
	}
}

void dptx_read_cr_reg(struct dptx *dptx)
{
	int i;
	uint32_t val;

	for (i = 0; i < sizeof(usb3dptx_phy_firmware) / sizeof(struct u3_phy_data); i++) {
		val = dptx_u3_phy_read_reg(dptx, usb3dptx_phy_firmware[i].addr);
		dptx_dbg(dptx, "%#x	%#x\n", usb3dptx_phy_firmware[i].addr, val);
	}
}

int dptx_wait_phy_boot_done(struct dptx *dptx, enum dptx_phy_boot_type boot_type) {
    u32 val;
    u32 phy_reg_val = 0;
    u8 retry = 10;
    int ret = 0;
    do {
		val = dptx_read_reg(dptx, dptx->regs[DPTX_CSR], EDP_CSR_PHY_STATE);
		if (val & BIT(1)) {
			dptx_info(dptx, "phy sram init done!\n");
			msleep(100);
			break;
		}
        retry--;
	} while(!(val & BIT(1)) && retry);

    if (!retry) {
        ret = -1;
        goto fail;
    }

	switch (boot_type) {
	case OVERRD_SRAM:
		dptx_write_cr_reg(dptx);
		val = dptx_read_reg(dptx, dptx->regs[DPTX_CSR], EDP_CSR_PHY_CTRL0);
		val |= BIT(10);
		dptx_write_reg(dptx, dptx->regs[DPTX_CSR], EDP_CSR_PHY_CTRL0, val);
		break;
	case ONLY_SRAM:
		dptx_write_cr_reg(dptx);
		val = dptx_read_reg(dptx, dptx->regs[DPTX_CSR], EDP_CSR_PHY_CTRL0);
		val &= ~BIT(10);
		dptx_write_reg(dptx, dptx->regs[DPTX_CSR], EDP_CSR_PHY_CTRL0, val);
		break;
	case ONLY_ROM_TRIG: /* Using the ROM contents directly */
		phy_reg_val = dptx_u3_phy_read_reg(dptx, RAWCMN_DIG_AON_CMN_SRAM_BL_CFG);
		phy_reg_val |= SRAM_BL_ROM;
		phy_reg_val |= SRAM_BL_BYPASS;
		phy_reg_val |= SRAM_BL_START;
		dptx_u3_phy_write_reg(dptx, RAWCMN_DIG_AON_CMN_SRAM_BL_CFG, phy_reg_val);
		break;
	case USE_SRAM_PREV_TRIG:  /* Overriding the SRAM using CREG */
		dptx_write_cr_reg(dptx);
		// bst_dptx_read_cr_reg(dptx);
		phy_reg_val = dptx_u3_phy_read_reg(dptx, RAWCMN_DIG_AON_CMN_SRAM_BL_CFG);
		phy_reg_val &= ~SRAM_BL_ROM;
		phy_reg_val |= SRAM_BL_BYPASS;
		phy_reg_val |= SRAM_BL_START;
		dptx_u3_phy_write_reg(dptx, RAWCMN_DIG_AON_CMN_SRAM_BL_CFG, phy_reg_val);
	break;
	case ROM_TO_SRAM_TRIG: /* Using the ROM contents but firmware runs from SRAM */
		phy_reg_val = dptx_u3_phy_read_reg(dptx, RAWCMN_DIG_AON_CMN_SRAM_BL_CFG);
		phy_reg_val &= ~SRAM_BL_ROM;
		phy_reg_val &= ~SRAM_BL_BYPASS;
		phy_reg_val |= SRAM_BL_START;
		dptx_u3_phy_write_reg(dptx, RAWCMN_DIG_AON_CMN_SRAM_BL_CFG, phy_reg_val);
	break;
	case OVERRD_SRAM_TRIG: /* Overriding the SRAM */
		// Write to RAWLANEN_DIG_FSM_FSM_OVRD_CTL a. FSM_OVRD_EN = 1 b. FSM_CMD_START = 1’b0 c. FSM_JMP_EN = 1’b0 d. FSM_JMP_ADDR = 12’d0
		phy_reg_val = dptx_u3_phy_read_reg(dptx, RAWLANEN_DIG_FSM_FSM_OVRD_CTL);
		phy_reg_val |= FSM_OVRD_EN;
		phy_reg_val &= ~FSM_CMD_START;
		phy_reg_val &= ~FSM_JMP_EN;
		phy_reg_val &= ~FSM_JMP_ADDR;
		dptx_u3_phy_write_reg(dptx, RAWLANEN_DIG_FSM_FSM_OVRD_CTL, phy_reg_val);

		phy_reg_val = dptx_u3_phy_read_reg(dptx, RAWCMN_DIG_AON_CMN_SRAM_BL_CFG);
		phy_reg_val &= ~SRAM_BL_ROM;
		phy_reg_val &= ~SRAM_BL_BYPASS;
		phy_reg_val |= SRAM_BL_START;
		dptx_u3_phy_write_reg(dptx, RAWCMN_DIG_AON_CMN_SRAM_BL_CFG, phy_reg_val);
		dptx_write_cr_reg(dptx);

		phy_reg_val = dptx_u3_phy_read_reg(dptx, RAWLANEN_DIG_FSM_FSM_OVRD_CTL);
		phy_reg_val &= ~FSM_OVRD_EN;
		phy_reg_val &= ~FSM_CMD_START;
		phy_reg_val &= ~FSM_JMP_EN;
		phy_reg_val &= ~FSM_JMP_ADDR;
		dptx_u3_phy_write_reg(dptx, RAWLANEN_DIG_FSM_FSM_OVRD_CTL, phy_reg_val);
	break;
	case SRAM_PREV_POR_TRIG: /* Using SRAM that was updated from previous POR but the contents were preserved */
		phy_reg_val = dptx_u3_phy_read_reg(dptx, RAWCMN_DIG_AON_CMN_SRAM_BL_CFG);
		phy_reg_val &= ~SRAM_BL_ROM;
		phy_reg_val |= SRAM_BL_BYPASS;
		phy_reg_val |= SRAM_BL_START;
		dptx_u3_phy_write_reg(dptx, RAWCMN_DIG_AON_CMN_SRAM_BL_CFG, phy_reg_val);
	break;
	case SRAM_PRE_FLASHED_TRIG: /* SRAM pre-flashed externally */
		phy_reg_val = dptx_u3_phy_read_reg(dptx, RAWCMN_DIG_AON_CMN_SRAM_BL_CFG);
		phy_reg_val &= ~SRAM_BL_ROM;
		phy_reg_val |= SRAM_BL_BYPASS;
		phy_reg_val |= SRAM_BL_START;
		dptx_u3_phy_write_reg(dptx, RAWCMN_DIG_AON_CMN_SRAM_BL_CFG, phy_reg_val);
	break;
	default:
		break;
	}

	// bst_dptx_read_cr_reg(dptx);

	dptx_dbg(dptx, "EDP_CSR_PHY_CTRL0:%#x\n", dptx_read_reg(dptx, dptx->regs[DPTX_CSR], EDP_CSR_PHY_CTRL0));
    return 0;
fail:
    return ret;
}