static inline void pcie_phy_write(struct pcie_phy *phy, u32 offset, u32 val)
{
	dw_pcie_write(phy->phy_base + offset, 4, val);
}

static inline u32 pcie_phy_read(struct pcie_phy *phy, u32 offset)
{
	u32 reg_val;

	dw_pcie_read(phy->phy_base + offset, 4, &reg_val);
	return reg_val;
}

static inline void pcie_phy_cfg(struct pcie_phy *phy, u64 reg, u32 val, u32 bit_mask)
{
	u32 reg_val;

	dw_pcie_read((phy->phy_base + reg), 4, &reg_val);
	reg_val &= ~bit_mask;
	reg_val |= (val << (ffs(bit_mask) - 1));
	dw_pcie_write(phy->phy_base + reg, 4, reg_val);
}

