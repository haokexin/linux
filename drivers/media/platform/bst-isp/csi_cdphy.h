static inline void csi_phy_set(struct csi_device *csi, u32 reg, u32 val)
{
	dev_dbg(csi->dev, "CPSET 0x%08X -> 0x%08X\n", reg, val);
	writel_relaxed(val, csi->ctrl_base + (reg << 2));
}

static inline u32 csi_phy_get(struct csi_device *csi, u32 reg)
{
	u32 val;

	val = readl_relaxed(csi->ctrl_base + (reg << 2));
	dev_dbg(csi->dev, "CPGET: 0x%08X -> 0x%08X\n", reg, val);

	return val;
}

